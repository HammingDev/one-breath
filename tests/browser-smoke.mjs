import { createRequire } from 'node:module';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const root = path.resolve(import.meta.dirname, '..');
await mkdir(path.join(root, 'output/playwright'), { recursive: true });
const profile = await mkdtemp(path.join(tmpdir(), 'one-breath-test-'));
const context = await chromium.launchPersistentContext(profile, {
  channel: 'chromium', headless: true, viewport: { width: 1280, height: 800 },
  args: [`--disable-extensions-except=${root}/extension`, `--load-extension=${root}/extension`]
});
const errors = [];
context.on('weberror', e => errors.push(e.error().message));
try {
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const id = new URL(worker.url()).host;
  const base = `chrome-extension://${id}/`;
  const page = await context.newPage();
  await page.goto(base + 'gate.html#https://x.com/search?q=design&f=live');
  await page.getByRole('heading', { name: '先呼吸，再决定。' }).waitFor();
  assert.equal(await page.locator('#begin').isDisabled(), true);
  const premature = await page.evaluate(() => chrome.runtime.sendMessage({ type: 'BEGIN', target: 'https://x.com/' }));
  assert.equal(premature.ok, false);
  console.log('PASS: gate requires completed exercise');
  await page.screenshot({ path: `${root}/output/playwright/breath.png`, fullPage: false });
  const settings = await context.newPage();
  await settings.goto(base + 'settings.html');
  assert.equal(await settings.locator('#temporary').inputValue(), '15');
  await settings.locator('#visit').fill('3');
  await settings.locator('#cooldown').fill('20');
  await settings.getByRole('button', { name: '保存偏好' }).click();
  await settings.getByText('已保存 · 下一次新会话生效').waitFor();
  await settings.screenshot({ path: `${root}/output/playwright/settings.png`, fullPage: false });
  // Synthetic responses exercise extension behavior without accessing an X account.
  await context.route(/^https:\/\/([^/]+\.)?(x\.com|twitter\.com)\//, route => route.fulfill({
    contentType: 'text/html', body: '<!doctype html><html><body><h1>Mock feed</h1><a href="/second">Next post</a><video></video></body></html>'
  }));
  await page.getByRole('button', { name: '开始浏览 3 分钟' }).waitFor({ state: 'visible', timeout: 20000 });
  await page.waitForFunction(() => !document.getElementById('begin').disabled);
  await page.locator('#begin').click();
  await page.waitForURL('https://x.com/search?q=design&f=live');
  await page.getByRole('heading', { name: 'Mock feed' }).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-one-breath-allowed'), '');
  let snapshot = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  const deadline = snapshot.state.endsAt;
  assert.equal(snapshot.state.cooldownMs, 20 * 60000);
  const second = await context.newPage();
  await second.goto('https://twitter.com/');
  await second.getByRole('heading', { name: 'Mock feed' }).waitFor();
  await second.reload();
  snapshot = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(snapshot.state.endsAt, deadline);
  await page.close();
  snapshot = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(snapshot.state.phase, 'active');
  await settings.locator('#cooldown').fill('1');
  await settings.getByRole('button', { name: '保存偏好' }).click();
  await second.goto('https://x.com/second');
  snapshot = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(snapshot.state.endsAt, deadline);
  console.log('PASS: deep link, multiple tabs, reload and domain switching share one deadline');
  await second.close();
  await settings.waitForFunction(async () => (await chrome.runtime.sendMessage({ type: 'STATUS' })).state.phase === 'cooldown');
  snapshot = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(snapshot.state.readyAt - snapshot.state.endedAt, 20 * 60000);
  console.log('PASS: closing last target starts cooldown; settings do not alter snapshot');
  const blocked = await context.newPage();
  await blocked.goto('https://x.com/home');
  await blocked.waitForURL(base + 'gate.html**');
  await blocked.getByRole('heading', { name: '休息一下。' }).waitFor();
  await blocked.screenshot({ path: `${root}/output/playwright/cooldown.png`, fullPage: false });
  assert.equal(await blocked.locator('#begin').isVisible(), false);
  console.log('PASS: cooldown intercepts network navigation');
  const originalReadyAt = snapshot.state.readyAt;
  await blocked.locator('#temporary').click();
  await blocked.waitForURL('https://x.com/home');
  await blocked.getByRole('heading', { name: 'Mock feed' }).waitFor();
  const temporary = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(temporary.state.readyAt, originalReadyAt);
  assert.equal(temporary.accessState.temporary, true);
  assert.ok(temporary.state.temporary.endsAt - Date.now() <= 900000);
  const extra = await context.newPage();
  await extra.goto('https://twitter.com/home');
  await extra.getByRole('heading', { name: 'Mock feed' }).waitFor();
  await blocked.reload();
  const afterReload = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(afterReload.state.temporary.endsAt, temporary.state.temporary.endsAt);
  const otherGate = await context.newPage();
  await otherGate.goto(base + 'gate.html');
  await otherGate.waitForFunction(() => document.querySelector('#title').textContent === '临时访问中。');
  await otherGate.evaluate(() => chrome.runtime.sendMessage({ type: 'TEMPORARY', target: 'https://x.com/' }));
  await otherGate.waitForURL('https://x.com/');
  const concurrent = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(concurrent.state.temporary.endsAt, temporary.state.temporary.endsAt);
  await otherGate.evaluate(() => { const editor = document.createElement('div'); editor.contentEditable = 'true'; editor.setAttribute('role', 'textbox'); editor.textContent = 'Unfinished draft'; document.body.append(editor); });
  const posting = await context.newPage();
  await posting.goto('https://x.com/posting');
  await posting.evaluate(() => { const button = document.createElement('button'); button.dataset.testid = 'tweetButtonInline'; button.textContent = 'Mock post'; document.body.append(button); });
  await posting.getByRole('button', { name: 'Mock post' }).click();
  await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'END' }));
  await blocked.waitForURL(base + 'gate.html**');
  await extra.waitForURL(base + 'gate.html**');
  assert.equal(otherGate.url(), 'https://x.com/');
  assert.equal(await otherGate.locator('[role=textbox]').textContent(), 'Unfinished draft');
  await otherGate.locator('[role=textbox]').fill('');
  await otherGate.evaluate(() => window.dispatchEvent(new Event('focus')));
  assert.equal(otherGate.url(), 'https://x.com/', 'protection stays latched after editor clears');
  assert.equal(posting.url(), 'https://x.com/posting', 'recent posting stays protected even without text');
  await posting.close();
  await otherGate.close();
  console.log('PASS: temporary end preserves draft tab while blocking ordinary tabs');
  const afterTemp = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(afterTemp.state.readyAt, originalReadyAt);
  assert.equal(afterTemp.state.temporary, undefined);
  await blocked.getByRole('heading', { name: '休息一下。' }).waitFor();
  await blocked.screenshot({ path: `${root}/output/playwright/temporary.png`, fullPage: false });
  // A custom one-minute session immediately exposes the warning and extension action.
  await settings.locator('#temporary').fill('1');
  await settings.getByRole('button', { name: '保存偏好' }).click();
  await blocked.getByRole('button', { name: '临时访问 · 1 分钟', exact: true }).waitFor();
  // Closing the final target page also ends a temporary session without resetting cooldown.
  await blocked.locator('#temporary').click();
  await blocked.waitForURL('https://x.com/home');
  const beforeExtension = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.ok(beforeExtension.state.temporary.endsAt - Date.now() <= 60000);
  // CDP can inspect the content script's closed shadow root without changing production code.
  const cdp = await context.newCDPSession(blocked);
  const { root: dom } = await cdp.send('DOM.getDocument', { depth: -1, pierce: true });
  function findExtend(node) {
    if (node.nodeName === 'BUTTON' && node.attributes?.includes('extend')) return node;
    for (const child of [...(node.children || []), ...(node.shadowRoots || [])]) { const found = findExtend(child); if (found) return found; }
  }
  const button = findExtend(dom);
  assert.ok(button);
  const { object } = await cdp.send('DOM.resolveNode', { nodeId: button.nodeId });
  const { result } = await cdp.send('Runtime.callFunctionOn', { objectId: object.objectId, functionDeclaration: 'function() { const visible = !this.hidden; this.click(); return visible; }', returnByValue: true });
  assert.equal(result.value, true);
  await settings.waitForFunction(async endsAt => (await chrome.runtime.sendMessage({ type: 'STATUS' })).state.temporary.endsAt === endsAt + 300000, beforeExtension.state.temporary.endsAt);
  const extended = await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }));
  assert.equal(extended.state.temporary.endsAt, beforeExtension.state.temporary.endsAt + 300000);
  assert.equal(extended.state.readyAt, originalReadyAt);
  console.log('PASS: configurable temporary duration, one-minute warning and five-minute extension');
  await blocked.close();
  await settings.waitForFunction(async () => !(await chrome.runtime.sendMessage({ type: 'STATUS' })).state.temporary);
  assert.equal((await settings.evaluate(() => chrome.runtime.sendMessage({ type: 'STATUS' }))).state.readyAt, originalReadyAt);
  console.log('PASS: temporary access, shared timer, reload, concurrent start, early end and last-tab close retain cooldown');
  assert.deepEqual(errors, []);
  console.log('PASS: no uncaught browser errors');
} finally { await context.close(); await rm(profile, { recursive: true, force: true }); }
